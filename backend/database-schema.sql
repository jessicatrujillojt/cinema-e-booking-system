CREATE SCHEMA IF NOT EXISTS CES_SCHEMA;
SET SCHEMA CES_SCHEMA;

-- =====================================================
-- Database: H2
-- =====================================================


-- =========================
-- USER
-- Named user_account because USER can be reserved in H2
-- =========================
CREATE TABLE user_account (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email_address VARCHAR(255) NOT NULL UNIQUE,
    phone_number VARCHAR(25),
    password VARCHAR(255) NOT NULL
);


-- =========================
-- CUSTOMER
-- Customer is a subtype of User
-- =========================
CREATE TABLE customer (
    user_id BIGINT PRIMARY KEY,
    status VARCHAR(20) NOT NULL,
    preferences VARCHAR(500),
    promotion_subscriptions BOOLEAN DEFAULT FALSE,

    CONSTRAINT fk_customer_user
        FOREIGN KEY (user_id)
        REFERENCES user_account(user_id),

    CONSTRAINT chk_customer_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);


-- =========================
-- ADMIN
-- Admin is a subtype of User
-- =========================
CREATE TABLE admin (
    user_id BIGINT PRIMARY KEY,

    CONSTRAINT fk_admin_user
        FOREIGN KEY (user_id)
        REFERENCES user_account(user_id)
);


-- =========================
-- ADDRESS
-- UNIQUE user_id means one address per user
-- =========================
CREATE TABLE address (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    street VARCHAR(255),
    city VARCHAR(100),
    state VARCHAR(50),
    zip_code VARCHAR(20),

    CONSTRAINT fk_address_user
        FOREIGN KEY (user_id)
        REFERENCES user_account(user_id)
);


-- =========================
-- PAYMENT CARD
-- =========================
CREATE TABLE payment_card (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    card_number VARCHAR(255) NOT NULL,
    exp_date VARCHAR(10) NOT NULL,
    mailing_address VARCHAR(255),

    CONSTRAINT fk_payment_card_user
        FOREIGN KEY (user_id)
        REFERENCES user_account(user_id)
);


-- =========================
-- PROMOTION
-- =========================
CREATE TABLE promotion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    discount_percent DECIMAL(5,2) NOT NULL,
    expiration_date DATE,
    active BOOLEAN DEFAULT TRUE,

    CONSTRAINT chk_discount_percent
        CHECK (discount_percent >= 0 AND discount_percent <= 100)
);


-- =========================
-- MOVIE
-- =========================
CREATE TABLE movie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    category VARCHAR(100),
    movie_cast VARCHAR(1000),
    director VARCHAR(255),
    producer VARCHAR(255),
    synopsis VARCHAR(2000),
    reviews VARCHAR(2000),
    trailer_image VARCHAR(1000),
    trailer_video VARCHAR(1000),
    rating_code VARCHAR(50),
    show_date DATE,
    show_time TIME,
    mpaa_rating VARCHAR(10),

    CONSTRAINT chk_mpaa_rating
        CHECK (
            mpaa_rating IS NULL
            OR mpaa_rating IN ('G', 'PG', 'PG-13', 'R', 'NC-17')
        )
);


-- =========================
-- CUSTOMER FAVORITES MOVIE
-- =========================
CREATE TABLE customer_favorites_movie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,

    CONSTRAINT fk_favorite_movie
        FOREIGN KEY (movie_id)
        REFERENCES movie(id),

    CONSTRAINT fk_favorite_customer
        FOREIGN KEY (user_id)
        REFERENCES customer(user_id),

    CONSTRAINT unique_customer_favorite
        UNIQUE (movie_id, user_id)
);


-- =========================
-- RECOMMENDATIONS
-- =========================
CREATE TABLE recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,

    CONSTRAINT fk_recommendations_customer
        FOREIGN KEY (user_id)
        REFERENCES customer(user_id)
);


-- =========================
-- RECOMMENDS MOVIES
-- Connects recommendations to movies
-- =========================
CREATE TABLE recommends_movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id BIGINT NOT NULL,
    movie_id BIGINT NOT NULL,

    CONSTRAINT fk_recommends_recommendation
        FOREIGN KEY (recommendation_id)
        REFERENCES recommendations(id),

    CONSTRAINT fk_recommends_movie
        FOREIGN KEY (movie_id)
        REFERENCES movie(id),

    CONSTRAINT unique_recommended_movie
        UNIQUE (recommendation_id, movie_id)
);


-- =========================
-- THEATRE
-- =========================
CREATE TABLE theatre (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);


-- =========================
-- SHOWROOM
-- =========================
CREATE TABLE showroom (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    theatre_id BIGINT NOT NULL,
    number_of_seats INT NOT NULL,

    CONSTRAINT fk_showroom_theatre
        FOREIGN KEY (theatre_id)
        REFERENCES theatre(id),

    CONSTRAINT chk_number_of_seats
        CHECK (number_of_seats >= 0)
);


-- =========================
-- SHOW
-- Named movie_show because SHOW is an SQL keyword
-- =========================
CREATE TABLE movie_show (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id BIGINT NOT NULL,
    showroom_id BIGINT NOT NULL,
    show_date DATE NOT NULL,
    show_time TIME NOT NULL,
    duration INT,

    CONSTRAINT fk_show_movie
        FOREIGN KEY (movie_id)
        REFERENCES movie(id),

    CONSTRAINT fk_show_showroom
        FOREIGN KEY (showroom_id)
        REFERENCES showroom(id)
);


-- =========================
-- SEAT
-- =========================
CREATE TABLE seat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    showroom_id BIGINT NOT NULL,
    row_number VARCHAR(10) NOT NULL,
    seat_number INT NOT NULL,

    CONSTRAINT fk_seat_showroom
        FOREIGN KEY (showroom_id)
        REFERENCES showroom(id),

    CONSTRAINT unique_showroom_seat
        UNIQUE (showroom_id, row_number, seat_number)
);


-- =========================
-- TICKET PRICE
-- =========================
CREATE TABLE ticket_price (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_type VARCHAR(20) NOT NULL,
    amount DECIMAL(10,2) NOT NULL,

    CONSTRAINT chk_ticket_price_type
        CHECK (ticket_type IN ('ADULT', 'SENIOR', 'CHILD')),

    CONSTRAINT chk_ticket_price_amount
        CHECK (amount >= 0)
);


-- =========================
-- BOOKING
-- =========================
CREATE TABLE booking (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    promotion_id BIGINT,
    show_id BIGINT NOT NULL,
    booking_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    subtotal DECIMAL(10,2) NOT NULL,
    discount_amount DECIMAL(10,2) DEFAULT 0,
    total_amount DECIMAL(10,2) NOT NULL,

    CONSTRAINT fk_booking_customer
        FOREIGN KEY (user_id)
        REFERENCES customer(user_id),

    CONSTRAINT fk_booking_promotion
        FOREIGN KEY (promotion_id)
        REFERENCES promotion(id),

    CONSTRAINT fk_booking_show
        FOREIGN KEY (show_id)
        REFERENCES movie_show(id),

    CONSTRAINT chk_booking_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED'))
);


-- =========================
-- TICKET
-- =========================
CREATE TABLE ticket (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL,
    price_id BIGINT NOT NULL,
    show_id BIGINT NOT NULL,
    ticket_type VARCHAR(20) NOT NULL,
    price_paid DECIMAL(10,2) NOT NULL,

    CONSTRAINT fk_ticket_booking
        FOREIGN KEY (booking_id)
        REFERENCES booking(booking_id),

    CONSTRAINT fk_ticket_seat
        FOREIGN KEY (seat_id)
        REFERENCES seat(id),

    CONSTRAINT fk_ticket_price
        FOREIGN KEY (price_id)
        REFERENCES ticket_price(id),

    CONSTRAINT fk_ticket_show
        FOREIGN KEY (show_id)
        REFERENCES movie_show(id),

    CONSTRAINT chk_ticket_type
        CHECK (ticket_type IN ('ADULT', 'SENIOR', 'CHILD')),

    CONSTRAINT chk_ticket_price_paid
        CHECK (price_paid >= 0),

    CONSTRAINT unique_show_seat
        UNIQUE (show_id, seat_id)
);